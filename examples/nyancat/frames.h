// Character-to-256-color mapping, copied from klange/nyancat's nyancat.c
// (the `colors[]` table, 256-color branch). Returns -1 for an unmapped
// character.
static inline int kCatColorIndex(char ch) {
    switch (ch) {
        case ',':  return 17;  // Blue background
        case '.':  return 231; // White stars
        case '\'': return 16;  // Black border
        case '@':  return 230; // Tan poptart
        case '$':  return 175; // Pink poptart
        case '-':  return 162; // Red poptart
        case '>':  return 196; // Red rainbow
        case '&':  return 214; // Orange rainbow
        case '+':  return 226; // Yellow rainbow
        case '#':  return 118; // Green rainbow
        case '=':  return 33;  // Light blue rainbow
        case ';':  return 19;  // Dark blue rainbow
        case '*':  return 240; // Gray cat face
        case '%':  return 175; // Pink cheeks
        default:   return -1;
    }
}

